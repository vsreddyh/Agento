#!/usr/bin/env bash
# OS-cron bridge for scheduled prompts (#490).
#
# Schedules used to tick inside pi-gateway (internal/cronjobs.Worker). They
# now live in the host crontab so they keep firing with the pi container
# stopped, and each fire runs `opencode run` from the repo root — which is
# what makes opencode.json's MCP servers (task-manager, project-manager, …)
# available to the turn.
#
# Commands:
#   install   read cron_jobs, cache the prompts, install the crontab block
#   dry-run   print the exact crontab block; write nothing
#   remove    remove the managed crontab block
#   list      show the generated jobs
#   run <id>  fire one job (what the crontab lines execute)
#   check     log fires missed while the host was down (start/restart, and
#             init right after install, call this)
#
# The crontab block is generated by cmd/t3-cron because the host cron daemon
# has no per-user timezone: the IST schedules are converted to the daemon's
# fixed offset at install time. See internal/cronjobs/osentry.go.
set -euo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"
BIN="$REPO/bin/t3-cron"
LOG="$REPO/run/t3-cron.log"

# shellcheck source=scripts/lib/common.sh
. "$REPO/scripts/lib/common.sh"

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; NC='\033[0m'
info() { echo -e "${GREEN}[INFO]${NC}  $*"; }
warn() { echo -e "${YELLOW}[WARN]${NC}  $*"; }
error() { echo -e "${RED}[ERROR]${NC} $*"; }

usage() {
    cat <<EOF
Usage: $(basename "$0") <command>

Commands:
  install       Convert cron_jobs into host crontab entries (writes $BIN cache)
  dry-run       Print the exact crontab entries; no writes
  remove        Remove the managed crontab block
  list          List the generated jobs
  run <id>      Fire one job via opencode run (crontab uses this)
  check         Log scheduled fires missed while the host was down
EOF
}

# cron invokes us with a minimal environment: make the installer's symlink
# and the per-user install location both reachable for `opencode run`.
export PATH="$HOME/.opencode/bin:/usr/local/bin:$PATH"
export T3_CRON_REPO="$REPO"

# log_fail is the loud fallback for failures that happen before the Go
# runner starts: a cron fire must never disappear silently. It always writes
# to stderr, then to the log, and falls back to syslog if the log is unwritable.
log_fail() {
    local msg="$*" line
    line="$(date -Iseconds 2>/dev/null || date) fire status=FAILED error=\"$msg\""
    echo "t3-cron: $msg" >&2
    if mkdir -p "$(dirname "$LOG")" 2>/dev/null && echo "$line" >> "$LOG" 2>/dev/null; then
        return 0
    fi
    command -v logger >/dev/null 2>&1 && logger -t t3-cron "$line" || true
}

build_bin() {
    if ! command -v go &>/dev/null; then
        echo "go toolchain not found — install Go (needed to build bin/t3-cron; MCP binaries need it too)" >&2
        return 1
    fi
    info "Building $BIN ..."
    ( cd "$REPO" && go build -trimpath -o "$BIN" ./cmd/t3-cron )
}

# install/dry-run/list may build on demand (interactive commands). run/check
# are invoked by cron and must never compile at fire time.
need_bin() {
    [[ -x "$BIN" ]] && return 0
    build_bin
}

case "${1:-help}" in
    install)
        load_root_env
        need_bin || exit 1
        exec "$BIN" install
        ;;
    dry-run)
        load_root_env
        need_bin || exit 1
        exec "$BIN" dry-run
        ;;
    remove)
        # Keep this independent of Go: clean must remove the block even on a
        # host where the binary was never built.
        if ! command -v crontab &>/dev/null; then
            warn "crontab not found — nothing to remove."
            exit 0
        fi
        mkdir -p "$REPO/run"
        {
            flock -n 9 || { warn "cron update already in progress — skipping removal."; exit 0; }
            ( crontab -l 2>/dev/null | sed '/^# >>> t3-cron/,/^# <<< t3-cron/d' || true ) | crontab - || true
            info "t3-cron crontab block removed."
        } 9>"$REPO/run/cron.lock"
        ;;
    list)
        load_root_env
        need_bin || exit 1
        exec "$BIN" list
        ;;
    check)
        # Miss reconciliation only; a missing binary means no jobs were ever
        # installed, so there is nothing to report.
        if [[ ! -x "$BIN" ]]; then
            echo "t3-cron: $BIN missing — run install first; skipping miss check." >&2
            exit 0
        fi
        load_root_env
        exec "$BIN" check
        ;;
    run)
        shift || true
        if [[ $# -ne 1 ]]; then
            log_fail "run requires exactly one job id"
            exit 2
        fi
        if [[ ! -x "$BIN" ]]; then
            log_fail "bin/t3-cron missing — run scripts/t3-cron.sh install"
            exit 1
        fi
        # The crontab fields are host-local; the fire itself speaks IST so the
        # prompt reads the wall clock its schedule was entered in. Set here,
        # not globally: install/dry-run must keep the host zone to convert.
        load_root_env
        export TZ="${T3_CRON_TZ:-Asia/Kolkata}"
        exec "$BIN" run "$1"
        ;;
    help|--help|-h)
        usage
        ;;
    *)
        error "Unknown command: $1"
        usage
        exit 1
        ;;
esac
